import re,sys
t=open(sys.argv[1],encoding='utf-8').read()
body=t.split('\n---\n')[0]
body='\n'.join(l for l in body.split('\n') if not l.startswith('#'))
chk={
'違禁/口語':['嘛','啦','挺','蠻','搞','弄','其實','反正','總之','說白了','東西','一下子','打個比方'],
'元話語/報幕':['下稱','如實','在案','後文','上文所述','本節將','如下：','在此寫明','一併交出','就此定稿','同步立檔','記在明處','兌現','本文將','筆者','我們認為'],
'對稱格言':['不是.{1,12}而是','並非.{1,12}而是'],
'序數鏈':['首先','其次','再次','其一','其二','其三','第一條','第二條','頭一條'],
'自鑄詞清單':['閘門','檔位','印記','刻度','界樁','凍結','底冊','候選池','旗標','回填','落座','幅面','歸簿','入判[^定]','合讀','初判','重判','封存','回接','判讀者'],
'章節自指':['本節','本章','第[一二三四五六七八九十]+[節章]','前節','導論'],
}
for k,v in chk.items():
    hits=[m.group(0) for p in v for m in re.finditer(p,body)]
    print(f'{k}: {len(hits)} {sorted(set(hits))}')
print('破折號(組):',body.count('——'))
print('本文:',body.count('本文'))
print('冒號',body.count('：'),'分號',body.count('；'),'句號',body.count('。'),'漢字',len(re.findall(r'[一-鿿]',body)))
